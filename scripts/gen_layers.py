"""gen_layers.py -- write lean/GrundyStrong/Layers.lean: the layers of the exhaustive search for the
octahedron and for H_21, each layer a balanced binary search tree of dominated masks.

Layer 0 is {0}; layer k+1 holds D | mask(v) for every D in layer k and every vertex v with
D | mask(v) != D. The Lean file checks, in the kernel, that every successor of layer k lies in
layer k+1 and that the last layer has no successors.

Usage: python3 scripts/gen_layers.py > lean/GrundyStrong/Layers.lean"""
import sys


def masks(n, cl):
    return [sum(1 << w for w in range(n) if cl(v, w)) for v in range(n)]


def layers(n, mk):
    L = [{0}]
    while True:
        nxt = {D | m for D in L[-1] for m in mk if D | m != D}
        if not nxt:
            return L
        L.append(nxt)


def tree(xs):
    if not xs:
        return ".leaf"
    m = len(xs) // 2
    return f"(.node {tree(xs[:m])} {xs[m]} {tree(xs[m + 1:])})"


def emit(name, n, mk, doc):
    L = layers(n, mk)
    print(f"/-! {doc} Layer `k` has {', '.join(str(len(x)) for x in L)} masks for `k = 0, …, {len(L) - 1}`. -/\n")
    for k, x in enumerate(L):
        print(f"def {name}{k} : Tree :=\n  {tree(sorted(x))}\n")
    print(f"def {name} : List Tree := [{', '.join(f'{name}{k}' for k in range(len(L)))}]\n")
    return L


oct_cl = lambda u, w: u == w or (u + 3 != w and w + 3 != u)
h_cl = lambda u, w: u == w or abs(u - w) % 3 == 2
print("import GrundyStrong.Search\n")
print("/-! Generated by `scripts/gen_layers.py`; do not edit by hand. -/\n")
print("namespace GrundyStrong\n")
print("set_option maxRecDepth 100000\n")
Lo = emit("octLayers", 6, masks(6, oct_cl), "The layers of the search for the octahedron.")
Lh = emit("hLayers", 21, masks(21, h_cl), "The layers of the search for `H_21`.")
print("end GrundyStrong")
print(f"octahedron: {len(Lo) - 1} = longest legal sequence; H_21: {len(Lh) - 1}", file=sys.stderr)
